def generate_pdf_report(history: list, user_name: str) -> bytes:
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.lib import colors
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Table, TableStyle, Spacer
        from reportlab.lib.enums import TA_CENTER, TA_LEFT

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=A4,
                                topMargin=2*cm, bottomMargin=2*cm,
                                leftMargin=2*cm, rightMargin=2*cm)
        styles = getSampleStyleSheet()
        story = []

        title_style = ParagraphStyle("title", parent=styles["Title"],
                                     textColor=colors.HexColor("#1e3a5f"),
                                     fontSize=18, spaceAfter=6)
        meta_style = ParagraphStyle("meta", parent=styles["Normal"],
                                    textColor=colors.grey, fontSize=9, spaceAfter=4)
        notice_style = ParagraphStyle("notice", parent=styles["Normal"],
                                      textColor=colors.HexColor("#b45309"),
                                      fontSize=8, spaceAfter=12,
                                      backColor=colors.HexColor("#fef3c7"),
                                      leftIndent=10, rightIndent=10)

        story.append(Paragraph("🔍 OSINT Bot — Search Report", title_style))
        story.append(Paragraph(
            f"User: {user_name} | Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')} | Searches: {len(history)}",
            meta_style
        ))
        story.append(Spacer(1, 0.3*cm))
        story.append(Paragraph(
            "⚠️ LEGAL NOTICE: This report contains publicly available data only. "
            "Use responsibly and in compliance with applicable laws.",
            notice_style
        ))
        story.append(Spacer(1, 0.5*cm))

        table_data = [["#", "Type", "Query", "Summary", "Date"]]
        for i, h in enumerate(history, 1):
            table_data.append([
                str(i),
                h["query_type"].upper(),
                h["query_value"][:30],
                h["result_summary"][:40] if h["result_summary"] else "",
                h["created_at"][:16]
            ])

        table = Table(table_data, colWidths=[1*cm, 2.5*cm, 4*cm, 6*cm, 3.5*cm])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a5f")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 8),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
            ("FONTSIZE", (0, 1), (-1, -1), 7.5),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("PADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(table)

        doc.build(story)
        buffer.seek(0)
        return buffer.read()
    except ImportError:
        logger.warning("reportlab not installed, returning txt fallback")
        return generate_txt_report(history, user_name)


@ban_checker_middleware
async def generate_report(update: Update, context: ContextTypes.DEFAULT_TYPE):
    fmt = context.args[0].lower() if context.args else "txt"
    if fmt not in ("txt", "html", "pdf"):
        await update.message.reply_text(
            "Usage: /report `<format>`\n\nFormats: `txt`, `html`, `pdf`",
            parse_mode="Markdown"
        )
        return

    user = update.effective_user
    history = get_user_history(user.id, limit=50)

    if not history:
        await update.message.reply_text(
            "📭 No search history found. Run some searches first!"
        )
        return

    await update.message.reply_text(f"📊 Generating *{fmt.upper()}* report...", parse_mode="Markdown")

    user_name = user.username or user.first_name or str(user.id)

    if fmt == "txt":
        data = generate_txt_report(history, user_name)
        await update.message.reply_document(
            document=io.BytesIO(data),
            filename=f"osint_report_{user_name}_{datetime.utcnow().strftime('%Y%m%d_%H%M')}.txt",
            caption="📄 Your OSINT search history report (TXT)"
        )
    elif fmt == "html":
        data = generate_html_report(history, user_name)
        await update.message.reply_document(
            document=io.BytesIO(data),
            filename=f"osint_report_{user_name}_{datetime.utcnow().strftime('%Y%m%d_%H%M')}.html",
            caption="🌐 Your OSINT search history report (HTML)"
        )
    elif fmt == "pdf":
        data = generate_pdf_report(history, user_name)
        await update.message.reply_document(
            document=io.BytesIO(data),
            filename=f"osint_report_{user_name}_{datetime.utcnow().strftime('%Y%m%d_%H%M')}.pdf",
            caption="📑 Your OSINT search history report (PDF)"
        )
