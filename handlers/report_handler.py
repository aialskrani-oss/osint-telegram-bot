"""
Report generation handler — TXT, HTML, PDF.
"""
import io
import os
import logging
from datetime import datetime
from telegram import Update
from telegram.ext import ContextTypes
from database.db import get_user_history
from middleware.ban_checker import ban_checker_middleware

logger = logging.getLogger(__name__)


def generate_txt_report(history: list, user_name: str) -> bytes:
    lines = [
        "=" * 60,
        "OSINT BOT - SEARCH HISTORY REPORT",
        f"User: {user_name}",
        f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}",
        "=" * 60,
        "",
        "LEGAL NOTICE: This report contains publicly available data only.",
        "Do not use for illegal purposes.",
        "",
        "-" * 60,
        "SEARCH HISTORY",
        "-" * 60,
        ""
    ]
    for i, h in enumerate(history, 1):
        lines.append(f"{i}. [{h['query_type'].upper()}] {h['query_value']}")
        lines.append(f"   Result: {h['result_summary']}")
        lines.append(f"   Date:   {h['created_at']}")
        lines.append("")
    lines.append("=" * 60)
    lines.append("END OF REPORT")
    return "\n".join(lines).encode("utf-8")


